-- Kichele Link migration 000: audited live schema baseline (structure only).
--
-- Bring a fresh environment to the audited live structure:
--   supabase/audit/live_schema_20261030.sql (2026-10-30)
--
-- Policy, trigger, RPC and grant work is applied by the later migrations
-- (002, 003, 004). This file creates the identity tables, keys and indexes
-- only, and leaves row level security enabled with no policies (deny by
-- default) so nothing is reachable before hardening is applied.

begin;

-- ---------------------------------------------------------------------------
-- gigs
-- ---------------------------------------------------------------------------
create table if not exists public.gigs (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    poster_id uuid not null references auth.users (id) on delete cascade,
    title text not null,
    description text not null,
    location text,
    budget numeric,
    status text not null default 'open',
    category text,
    agreed_price numeric,
    payment_status text not null default 'unpaid'
);

-- ---------------------------------------------------------------------------
-- applications
-- ---------------------------------------------------------------------------
create table if not exists public.applications (
    id bigint generated by default as identity primary key,
    gig_id bigint not null references public.gigs (id) on delete cascade,
    worker_id uuid not null references auth.users (id) on delete cascade,
    message text,
    status text not null default 'pending',
    created_at timestamptz not null default now(),
    constraint applications_one_per_worker_per_gig unique (gig_id, worker_id)
);

-- ---------------------------------------------------------------------------
-- payment_transactions
-- ---------------------------------------------------------------------------
create table if not exists public.payment_transactions (
    id bigint generated by default as identity primary key,
    gig_id bigint not null references public.gigs (id) on delete cascade,
    payer_id uuid not null references auth.users (id) on delete cascade,
    worker_id uuid not null references auth.users (id) on delete cascade,
    amount numeric not null,
    status text not null default 'pending',
    payment_method text,
    provider text,
    provider_transaction_id text,
    created_at timestamptz not null default now(),
    paid_at timestamptz,
    checkout_request_id text,
    merchant_request_id text,
    phone_number text,
    mpesa_receipt_number text,
    result_code integer,
    result_desc text,
    callback_received_at timestamptz,
    constraint payment_transactions_amount_check check (amount > 0)
);

create unique index if not exists payment_transactions_checkout_request_id_unique
    on public.payment_transactions (checkout_request_id)
    where checkout_request_id is not null;

-- ---------------------------------------------------------------------------
-- profiles
-- ---------------------------------------------------------------------------
create table if not exists public.profiles (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    full_name text,
    user_id uuid unique,
    phone text,
    location text
);

comment on table public.profiles is 'User profiles for Kichele Link';

-- ---------------------------------------------------------------------------
-- Row level security is enabled immediately; policies arrive with the
-- hardening migrations (002, 004).
-- ---------------------------------------------------------------------------
alter table public.gigs enable row level security;
alter table public.applications enable row level security;
alter table public.payment_transactions enable row level security;
alter table public.profiles enable row level security;

-- Client table access is granted later (004). Nothing here is granted to
-- anon or authenticated on purpose: a policy-less RLS table denies access,
-- so the deny-by-default cover holds from the first apply.

commit;

