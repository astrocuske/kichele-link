CREATE OR REPLACE FUNCTION "public"."worker_has_accepted_application"("gig_id_input" bigint) RETURNS boolean
    LANGUAGE "sql" SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
    select exists (
        select 1
        from public.applications
        where applications.gig_id = gig_id_input
          and applications.worker_id = auth.uid()
          and applications.status = 'accepted'
    );
$$;


